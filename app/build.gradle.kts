// keystore.properties is git-ignored. Without it, release builds are left unsigned
// instead of silently falling back to the debug key (which Play rejects).
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "com.personal.game2048"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.personal.game2048"
        minSdk = 24
        targetSdk = 36
        versionCode = 2
        versionName = "2.0.0"

        val url = (project.findProperty("leaderboardUrl") as String? ?: "").trim().trimEnd('/')
        buildConfigField("String", "LEADERBOARD_URL", "\"$url\"")
    }

    signingConfigs {
        if (keystoreProps.isNotEmpty()) {
            create("upload") {
                storeFile = file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("upload")
        }
    }

    compileOptions {
        isCoreLibraryDesugaringEnabled = true
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    packaging {
        resources.excludes += "/META-INF/{AL2.0,LGPL2.1}"
